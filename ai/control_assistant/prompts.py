def chat_user(question: str, facts: dict) -> str:
    """질문 + 사실.

    ⛔ 예전 머리말이 **"조회 데이터:"**였다. 규칙 줄에서는 "조회 데이터 같은 내부 낱말을
    쓰지 마라"고 시켜 놓고 **우리가 그 낱말을 먼저 보여준 것**이라, 모델이 그대로 따라
    "현재 조회 데이터에는…"으로 답했다(2026-08-07 실사용). 규칙보다 본보기가 세다.

    ⭐ **질문에 맞는 칸만 싣는다**(2026-08-07). 프리필이 디코딩보다 큰 것을 실측으로
    확인했고(3.47초 대 2.58초), 그 프리필의 절반 넘게가 사실 딕셔너리다. 자세한 근거는
    `facts_select` 머리말에 있다.

    ⛔ **사실 딕셔너리에 섞여 들어온 지시문을 중화한다**(2026-08-07). 그 값들은 DB 에서
    오고 DB 에는 요원이 적은 문자열이 섞인다. 자세한 근거는 `injection` 머리말에 있다.
    """
    picked = facts_select.pick(question, facts)
    safe_facts, _ = injection.sanitize(_annotate(picked))
    safe_q, _ = injection.sanitize_question(question)
    return f"질문: {safe_q}\n\n지금 관제 상태:\n{_as_json(safe_facts)}"
